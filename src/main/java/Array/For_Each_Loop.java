package Array;

public class For_Each_Loop {

    public static void main(String[] args) {

        String[] name = {"Emon", "Anika", "Promit", "Afia", "Samiul"};

        int[] number = {5, 6, 7, 8};

        for (int x : number) {
            System.out.println(x);
        }

        for (String y : name) {

            System.out.println(y);
        }
    }

}
